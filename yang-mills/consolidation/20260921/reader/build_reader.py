"""Assemble five unchanged proof sources and compile a mathematical reader.

Only the introduction/template are authored text. Source manuscripts are copied
verbatim into the Markdown assembly after newline/BOM handling, then typeset.
No mathematics is regenerated by this publication script.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
PUBLIC_BASE = ROOT.parent / "package/workbench/yang-mills/continuations"
SOURCES = [
    ("A", "20260921-heat-response-transfer/PHYSICAL_HEAT_COEFFICIENTS.md"),
    ("B", "20260921-heat-response-transfer/HEAT_REMAINDER_AND_NATIVE_METRICS.md"),
    ("C", "20260921-heat-response-transfer/RH_HEAT_TRANSFER.md"),
    ("D", "20260921-volume-heat-return/VOLUME_UNIFORM_HEAT.md"),
    ("E", "20260921-volume-heat-return/GROWING_OBSERVATIONS_AND_COMPLEMENT.md"),
]
STEM = "yang_mills_heat_volume_20260921"

def sha(data):
    return hashlib.sha256(data).hexdigest()

def run(command, logfile):
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True,
                            encoding="utf-8", errors="replace", timeout=180)
    (ROOT / logfile).write_text(result.stdout + result.stderr, encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Build command failed; inspect {logfile}")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, help="Directory containing the two Sep21 continuation folders")
    parser.add_argument("--output-dir", type=Path, help="Destination for the compiled PDF")
    args = parser.parse_args()
    base = args.source_dir or PUBLIC_BASE
    if not base.is_dir():
        raise FileNotFoundError("Pass --source-dir pointing to package/workbench/yang-mills/continuations")
    introduction = (ROOT / "reader_introduction.md").read_text(encoding="utf-8")
    if "<!-- ATTRIBUTION INSERT -->" in introduction:
        raise RuntimeError("Awaiting verified attribution paragraph before final assembly")
    pieces, render_pieces, record = [introduction], [introduction], []
    for appendix, relative in SOURCES:
        path = base / relative
        data = path.read_bytes()
        source_text = data.decode("utf-8-sig").replace("\r\n", "\n")
        pieces.append(source_text)
        # The manuscripts use literal * for adjoints/multiplication and _ for
        # coordinates. Protect these from Markdown emphasis without changing
        # the canonical assembled source. Indented formula blocks are verbatim.
        protected_lines = []
        for line in source_text.splitlines(keepends=True):
            if line.startswith("    "):
                protected_lines.append(line)
            else:
                protected_lines.append(line.replace("*", r"\*").replace("_", r"\_"))
        render_text = "".join(protected_lines)
        # Prove that the writer escapes remove to exactly the source bytes.
        recovered_lines = []
        for line in render_text.splitlines(keepends=True):
            recovered_lines.append(line if line.startswith("    ") else
                                   line.replace(r"\*", "*").replace(r"\_", "_"))
        if "".join(recovered_lines) != source_text:
            raise ValueError("Writer escape changed source: " + relative)
        render_pieces.append(render_text)
        record.append({"appendix": appendix, "source_path": relative,
                       "source_bytes": len(data), "source_sha256": sha(data),
                       "source_text_sha256": sha(source_text.encode()),
                       "formula_or_proof_edits": False})
    full = "\n\n".join(pieces)
    for appendix, relative in SOURCES:
        expected = (base / relative).read_text(encoding="utf-8-sig").replace("\r\n", "\n")
        if full.count(expected) != 1:
            raise ValueError("Source not present exactly once: " + relative)
    md = ROOT / (STEM + ".md")
    md.write_text(full, encoding="utf-8", newline="\n")
    render_md = ROOT / (STEM + "_render.md")
    render_md.write_text("\n\n".join(render_pieces), encoding="utf-8", newline="\n")
    (ROOT / "source_integrity.json").write_text(json.dumps({
        "schema": "ym-heat-volume-reader-source-integrity-v1",
        "integrity": "Five complete source texts included exactly once after UTF-8 BOM and line-ending handling only.",
        "sources": record, "assembled_markdown_sha256": sha(md.read_bytes()),
        "render_input_sha256": sha(render_md.read_bytes()),
        "render_protection": "Literal asterisks and underscores outside indented code are Markdown-escaped. The inverse escape was checked against every complete source text. Smart punctuation and raw HTML/TeX parsing are disabled for the assembled render.",
    }, indent=2) + "\n", encoding="utf-8")
    run(["pandoc", str(render_md), "--from=markdown+tex_math_single_backslash-superscript-subscript-raw_tex-raw_html-smart",
         "--to=latex", "--standalone", "--number-sections", "--toc", "--toc-depth=2",
         "--template=" + str(ROOT / "reader_template.tex"),
         "--lua-filter=" + str(ROOT / "inline_code.lua"),
         "--output=" + str(ROOT / (STEM + ".tex"))], "pandoc.log")
    for number in range(1, 3):
        run(["xelatex", "-interaction=nonstopmode", "-halt-on-error", "-no-shell-escape",
             "-recorder", STEM + ".tex"], f"xelatex-pass-{number}.log")
    output_dir = args.output_dir or ROOT / "output"
    target = output_dir / (STEM + ".pdf")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / (STEM + ".pdf"), target)
    print(json.dumps({"sources": len(record), "source_integrity": "pass",
                      "pdf": str(target), "bytes": target.stat().st_size,
                      "sha256": sha(target.read_bytes())}))

if __name__ == "__main__":
    main()
